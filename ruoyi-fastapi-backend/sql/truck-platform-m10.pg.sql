-- M10 GA/T1400 订阅、通知日志、过车记录表（PostgreSQL）
BEGIN;

CREATE TABLE IF NOT EXISTS gat1400_subscribe (
  subscribe_id     VARCHAR(64) PRIMARY KEY,
  title            VARCHAR(256) NOT NULL,
  subscribe_detail VARCHAR(128) NOT NULL,
  resource_uri     VARCHAR(256) NOT NULL,
  applicant_name   VARCHAR(64)  DEFAULT '',
  applicant_org    VARCHAR(128) DEFAULT '',
  begin_time       TIMESTAMP    NOT NULL,
  end_time         TIMESTAMP    NOT NULL,
  receive_addr     VARCHAR(256) NOT NULL,
  operate_type     CHAR(1)      NOT NULL DEFAULT '0',
  subscribe_status CHAR(1)      NOT NULL DEFAULT '0',
  cancel_org       VARCHAR(128) DEFAULT '',
  cancel_person    VARCHAR(32)  DEFAULT '',
  cancel_time      TIMESTAMP,
  cancel_reason    VARCHAR(64)  DEFAULT '',
  create_by        VARCHAR(64)  DEFAULT '',
  create_time      TIMESTAMP,
  update_by        VARCHAR(64)  DEFAULT '',
  update_time      TIMESTAMP,
  del_flag         CHAR(1)      NOT NULL DEFAULT '0'
);

CREATE INDEX IF NOT EXISTS idx_subscribe_end_time ON gat1400_subscribe (end_time);
COMMENT ON TABLE gat1400_subscribe IS 'GA/T1400订阅配置表';

CREATE TABLE IF NOT EXISTS gat1400_notify_log (
  notify_log_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id VARCHAR(64)  DEFAULT '',
  subscribe_id    VARCHAR(64)  DEFAULT '',
  trigger_time    TIMESTAMP,
  parse_status    VARCHAR(20)  NOT NULL DEFAULT 'success',
  record_count    INTEGER      NOT NULL DEFAULT 0,
  error_message   VARCHAR(500) DEFAULT '',
  raw_body        TEXT,
  create_time     TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_notification_id ON gat1400_notify_log (notification_id);
CREATE INDEX IF NOT EXISTS idx_notify_subscribe_id ON gat1400_notify_log (subscribe_id);
COMMENT ON TABLE gat1400_notify_log IS 'GA/T1400通知原始报文日志表';

CREATE TABLE IF NOT EXISTS truck_pass_record (
  record_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  motor_vehicle_id   VARCHAR(64) NOT NULL UNIQUE,
  info_kind          SMALLINT,
  device_id          VARCHAR(64),
  tollgate_id        VARCHAR(64),
  plate_no           VARCHAR(32),
  plate_class        VARCHAR(16),
  plate_color        VARCHAR(16),
  vehicle_class      VARCHAR(16),
  vehicle_color      VARCHAR(16),
  pass_time          TIMESTAMP,
  name_of_passed_road VARCHAR(64),
  lane_no            INTEGER,
  speed              INTEGER,
  direction          VARCHAR(16),
  has_plate          CHAR(1),
  is_suspicious      CHAR(1),
  storage_url1       VARCHAR(512),
  storage_url2       VARCHAR(512),
  storage_url3       VARCHAR(512),
  storage_url4       VARCHAR(512),
  storage_url5       VARCHAR(512),
  plate_reliability  VARCHAR(8),
  raw_json           JSONB,
  vehicle_id         BIGINT,
  create_time        TIMESTAMP,
  update_time        TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_pass_plate_no ON truck_pass_record (plate_no);
CREATE INDEX IF NOT EXISTS idx_pass_time ON truck_pass_record (pass_time);
CREATE INDEX IF NOT EXISTS idx_pass_device_id ON truck_pass_record (device_id);
COMMENT ON TABLE truck_pass_record IS 'GA/T1400过车记录表';

COMMIT;
